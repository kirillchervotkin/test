/**
 * Внутреннее представление роли на поле (доменная сущность).
 * Используется в репозитории и сервисе.
 *
 * Роль — глобальный справочник. Не привязана к турниру,
 * не имеет иерархии. Используется в назначениях
 * (`assignments.field_role_id`) для указания, кем является
 * судья на конкретном матче.
 *
 * Поля:
 *   - `code` — программный код ('REFEREE', 'ASSISTANT', 'RESERVE',
 *     'VAR', 'AVAR'). Уникален. Используется в бизнес-логике
 *     (например, «на матч должен быть назначен REFEREE») и как
 *     ключ локализации на фронте.
 *   - `name` — отображаемое имя на русском. Fallback для UI,
 *     если фронт не знает код.
 *   - `sortOrder` — порядок отображения в UI. Используется
 *     в ORDER BY при выборке ролей и в JOIN с назначениями.
 *
 * Локализация: перевод на другие языки делается на фронтенде
 * по `code`. Бэкенд отдаёт русский `name` как fallback.
 */
export interface FieldRole {
  id: string;
  code: string;
  name: string;
  sortOrder: number;
}

/**
 * Данные для создания роли.
 *
 * Отличается от `FieldRole`:
 *   - нет `id` — его генерирует репозиторий (uuidv4) или
 *     задаётся явно при сиде.
 *
 * Все поля обязательные: у роли есть код, имя и порядок.
 * Никаких nullable-полей нет — это упрощает create (не нужно
 * фильтровать null/undefined, как в городах или командах).
 *
 * Семантика на create-пути:
 *   `undefined` и `null` для этих полей недопустимы — тип
 *   требует их обязательного наличия. Валидация на уровне DTO.
 */
export interface CreateFieldRoleData {
  code: string;
  name: string;
  sortOrder: number;
}

/**
 * Данные для частичного обновления роли.
 *
 * Все поля кроме `id` — опциональны. `null` не допускается:
 * у роли нет nullable-полей, «обнулять» нечего.
 *
 * Семантика:
 *   - `undefined` — поле не передано, не трогаем в БД.
 *   - значение — заменить.
 *
 * `code` можно менять, но осторожно: он используется в
 * бизнес-логике и как ключ локализации. Обычно роли фиксированы
 * и не меняются. Если нужно переименовать — лучше через
 * явный сценарий, а не через общий PATCH.
 */
export type UpdateFieldRoleData = {
  id: string;
} & Partial<Omit<FieldRole, 'id'>>;

/**
 * Фильтры для поиска ролей.
 * Все поля опциональны — комбинируются через AND.
 */
export interface FieldRoleFilters {
  code?: string; // точное совпадение
  name?: string; // поиск по подстроке (LIKE %name%)
}
